// Builds the verification page's stylesheets from their sources.
//
//   verify-page.src.css   -> verify-page.css    (desktop: U(n) = n pixels of the 1062 px wide design)
//   verify-mobile.src.css -> verify-mobile.css  (mobile:  M(n) = n pixels of the 360 px wide design)
//
// U(13.5) becomes calc(var(--u) * 13.5) and M(13.5) becomes calc(var(--mu) * 13.5); each variable
// scales one design pixel to the window or phone. Run after editing a source:  npm run build:appo-css
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "appo-page");

const jobs = [
  { src: "verify-page.src.css", out: "verify-page.css", fn: "U", unit: "--u" },
  { src: "verify-mobile.src.css", out: "verify-mobile.css", fn: "M", unit: "--mu" },
];

for (const { src, out, fn, unit } of jobs) {
  const text = readFileSync(join(dir, src), "utf8");
  const call = new RegExp(`\\b${fn}\\((-?[0-9.]+)\\)`, "g");
  const result = text
    .replace(
      `SOURCE FILE. Edit this one, then run \`npm run build:appo-css\` to regenerate ${out}.`,
      `GENERATED from ${src} by \`npm run build:appo-css\`. Do not edit this file by hand.`,
    )
    .replace(call, (_, n) => `calc(var(${unit}) * ${n})`);
  const left = result.replace(/\/\*[\s\S]*?\*\//g, "").match(new RegExp(`\\b${fn}\\([^)]*\\)`, "g"));
  if (left) {
    console.error(`${src}: could not convert`, left.join(", "));
    process.exit(1);
  }
  writeFileSync(join(dir, out), result);
  console.log(`${out} written (${(result.match(new RegExp(`var\\(${unit}\\)`, "g")) ?? []).length} scaled values)`);
}
