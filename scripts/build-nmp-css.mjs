// Builds src/components/new-m-page/verify-page.css from verify-page.src.css.
//
// The source is written in design pixels of the 1062 px wide reference design: U(13.5) means 13.5
// design pixels and becomes calc(var(--u) * 13.5), where --u scales one design pixel to the window.
// Run after editing the source:  npm run build:nmp-css
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "new-m-page");
const src = readFileSync(join(dir, "verify-page.src.css"), "utf8");
const out = src
  .replace(" * SOURCE FILE. Edit this one, then run `npm run build:nmp-css` to regenerate verify-page.css.", " * GENERATED from verify-page.src.css by `npm run build:nmp-css`. Do not edit this file by hand.")
  .replace(/\bU\((-?[0-9.]+)\)/g, (_, n) => `calc(var(--u) * ${n})`);
const left = out.replace(/\/\*[\s\S]*?\*\//g, "").match(/\bU\([^)]*\)/g);
if (left) {
  console.error("Could not convert:", left.join(", "));
  process.exit(1);
}
writeFileSync(join(dir, "verify-page.css"), out);
console.log(`verify-page.css written (${(out.match(/var\(--u\)/g) ?? []).length} scaled values)`);
